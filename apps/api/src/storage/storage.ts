/**
 * Object storage behind an adapter (ADR-0012). Private verification documents live under
 * `private/`, images under `media/`. Clients never get storage credentials: they get short-lived
 * signed URLs scoped to one object, one method, one content type and a maximum size.
 */
export interface SignedUpload {
  url: string;
  method: 'PUT';
  headers: Record<string, string>;
  expiresAt: Date;
}

export interface SignedDownload {
  url: string;
  expiresAt: Date;
}

export interface StoredObject {
  size: number;
  contentType: string;
}

export interface ObjectStorage {
  signUpload(
    key: string,
    options: { contentType: string; maxBytes: number; expiresAt: Date },
  ): SignedUpload;
  signDownload(
    key: string,
    options: { expiresAt: Date; fileName?: string; disposition: 'inline' | 'attachment' },
  ): SignedDownload;
  head(key: string): Promise<StoredObject | null>;
  /** Reads at most `maxBytes + 1` bytes, so callers can detect oversize objects cheaply. */
  read(key: string, maxBytes: number): Promise<Buffer>;
  put(key: string, bytes: Uint8Array, contentType: string): Promise<void>;
  delete(key: string): Promise<void>;
}

export interface MalwareScanner {
  scan(bytes: Uint8Array): Promise<{ clean: boolean; signature?: string }>;
}

export const OBJECT_STORAGE = Symbol('OBJECT_STORAGE');
export const MALWARE_SCANNER = Symbol('MALWARE_SCANNER');

/** Keys are generated by the API; this guards the adapters against anything else. */
export const OBJECT_KEY = /^(private|media)\/[0-9a-f-]{36}\/[0-9a-f-]{36}\.(pdf|jpg|png|webp)$/;

export function extensionFor(contentType: string): 'pdf' | 'jpg' | 'png' | 'webp' {
  switch (contentType) {
    case 'application/pdf':
      return 'pdf';
    case 'image/jpeg':
      return 'jpg';
    case 'image/png':
      return 'png';
    case 'image/webp':
      return 'webp';
    default:
      throw new Error('unsupported content type');
  }
}
