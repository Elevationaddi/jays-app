import type { MessageKey } from '@jays/i18n';

/** Maps API error codes to UI copy. Unknown codes fall back to a generic message. */
export function errorMessageKey(code: string | undefined): MessageKey | null {
  switch (code) {
    case undefined:
    case '':
      return null;
    case 'INVALID_CREDENTIALS':
      return 'auth.error.invalidCredentials';
    case 'OTP_INVALID':
      return 'auth.error.otpInvalid';
    case 'OTP_EXPIRED':
      return 'auth.error.otpExpired';
    case 'OTP_ATTEMPTS_EXCEEDED':
      return 'auth.error.otpLocked';
    case 'SMS_UNAVAILABLE':
      return 'auth.error.smsUnavailable';
    case 'RATE_LIMITED':
    case 'OTP_RESEND_COOLDOWN':
    case 'OTP_SEND_LIMIT':
      return 'auth.error.rateLimited';
    case 'VALIDATION_FAILED':
      return 'auth.error.validation';
    case 'NETWORK_ERROR':
      return 'common.offline';
    case 'ADDON_LIMIT':
      return 'error.addonLimit';
    case 'PORTFOLIO_LIMIT':
      return 'error.portfolioLimit';
    case 'MEDIA_IN_USE':
      return 'error.mediaInUse';
    case 'MEDIA_NOT_READY':
      return 'error.mediaNotReady';
    case 'NOT_A_HOME_VISIT':
      return 'error.notAHomeVisit';
    case 'IN_REVIEW':
      return 'error.inReview';
    case 'PROFILE_LOCKED':
      return 'error.profileLocked';
    case 'ONBOARDING_INCOMPLETE':
      return 'error.onboardingIncomplete';
    case 'FILE_TYPE_MISMATCH':
    case 'CONTENT_TYPE_MISMATCH':
      return 'error.fileType';
    case 'FILE_TOO_LARGE':
      return 'error.fileTooLarge';
    case 'FILE_INFECTED':
      return 'error.fileInfected';
    case 'UPLOAD_FAILED':
      return 'error.uploadFailed';
    case 'SCANNER_UNAVAILABLE':
      return 'error.scannerUnavailable';
    case 'IMAGE_DIMENSIONS':
      return 'error.imageDimensions';
    case 'UPLOAD_EXPIRED':
    case 'UPLOAD_MISSING':
    case 'FILE_EMPTY':
      return 'error.uploadExpired';
    case 'VERSION_CONFLICT':
      return 'error.versionConflict';
    case 'INVALID_TRANSITION':
      return 'error.invalidTransition';
    case 'LICENSE_EXPIRED':
      return 'error.licenseExpired';
    case 'NOTHING_TO_SUBMIT':
      return 'error.nothingToSubmit';
    case 'SLUG_TAKEN':
      return 'error.slugTaken';
    case 'HAS_ACTIVE_CHILDREN':
      return 'error.hasChildren';
    case 'DEPTH_LIMIT':
      return 'error.depthLimit';
    case 'PARENT_INVALID':
      return 'error.parentInvalid';
    case 'STOREFRONT_INCOMPLETE':
      return 'error.storefrontIncomplete';
    case 'NO_PENDING_CHANGES':
      return 'error.noPendingChanges';
    case 'MODE_NOT_PENDING':
      return 'error.modeNotPending';
    case 'FORBIDDEN':
      return 'error.forbidden';
    case 'SKU_TAKEN':
    case 'DUPLICATE_SKU':
      return 'error.skuTaken';
    case 'PRODUCT_INCOMPLETE':
      return 'error.productIncomplete';
    case 'PRODUCT_IN_REVIEW':
      return 'error.productInReview';
    case 'INSUFFICIENT_STOCK':
      return 'error.insufficientStock';
    case 'LAST_VARIANT':
      return 'error.lastVariant';
    case 'OUT_OF_STOCK':
      return 'error.outOfStock';
    case 'QUOTE_STALE':
      return 'error.quoteStale';
    case 'QUOTE_EXPIRED':
      return 'error.quoteExpired';
    case 'DELIVERY_PARTNER_UNAVAILABLE':
      return 'error.deliveryPartnerUnavailable';
    case 'DELIVERY_UNAVAILABLE':
    case 'NO_DELIVERY_ZONE':
      return 'error.deliveryUnavailable';
    case 'CART_NOT_READY':
      return 'error.cartNotReady';
    case 'PAYMENT_PROVIDER_UNAVAILABLE':
      return 'error.paymentUnavailable';
    case 'SLOT_UNAVAILABLE':
      return 'error.slotUnavailable';
    case 'SCHEDULE_CONFLICT':
      return 'error.scheduleConflict';
    case 'TOO_EARLY':
      return 'error.tooEarly';
    case 'OUTSIDE_BOOKING_WINDOW':
      return 'error.outsideWindow';
    case 'SERVICE_SUSPENDED':
      return 'error.serviceSuspended';
    case 'HOME_SERVICES_NOT_APPROVED':
      return 'error.homeNotApproved';
    case 'HOME_PROFILE_LOCKED':
      return 'error.homeLocked';
    case 'HOME_PROFILE_INCOMPLETE':
      return 'error.homeIncomplete';
    case 'MEMBER_ALREADY_STAFF':
      return 'error.memberAlreadyStaff';
    case 'CANCEL_TOO_LATE':
      return 'error.cancelTooLate';
    case 'NOT_REFUNDABLE':
      return 'error.notRefundable';
    case 'MERCHANT_AGREEMENT_REQUIRED':
      return 'legal.error.agreementRequired';
    case 'VERSION_NOT_CURRENT':
      return 'legal.error.versionNotCurrent';
    case 'ALREADY_REPORTED':
      return 'error.alreadyReported';
    case 'BUSINESS_NOT_APPROVED':
      return 'error.businessNotApproved';
    default:
      return 'common.error';
  }
}
